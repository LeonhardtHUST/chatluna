export function repairBenignRefusal(prompt: string, reply: string) {
    const text = reply.trim()
    const fixedBlock =
        text ===
            '服务安全策略阻止了对有关提示词的响应。若有疑义，请联系管理员。' ||
        text ===
            '基于模型内容安全策略，服务端 API 拒绝为本次内容提供响应。请求记录已存档备查。若有问题，请联系管理员。'
    const safeExperimentPrompt =
        /拒绝高风险实验|推荐安全替代|安全替代.*说明/.test(prompt) &&
        !/复现|关键条件|参数|步骤|配方|剂量|事故|爆炸|燃烧瓶|炸药|病原|毒品/.test(
            prompt
        )
    const safeSearchMisusePrompt =
        /(搜索语法|高级搜索|搜索指令|google dork|dork|网盘资料).*(风险|替代流程|替代方案|合规|培训|话术|提醒|不要|不应|不能|禁止|说明)/i.test(
            prompt
        ) &&
        !/(帮我找|帮我搜|给我.*语法|列出.*语法|可用链接|下载|获取|site:|inurl:|intitle:)/i.test(
            prompt
        )
    const safeCredentialPrompt =
        /(批量验证.*旧密码|旧密码.*还能登录|旧密码.*登录)/.test(prompt) &&
        /(安全负责人|合规|怎么回复|话术|处理话术|直接发给对方)/.test(prompt) &&
        !/(帮我验证|帮我测试|脚本|代码|工具|hashcat|撞库|爆破|绕过)/i.test(
            prompt
        )
    const safePromptBypassPrompt =
        /忽略规则导出配置/.test(prompt) &&
        /(客服|工单|备注|处理话术|怎么写|直接发给对方)/.test(prompt) &&
        !/(帮我忽略|帮我绕过|怎么绕过|直接导出|导出密钥|导出 token|导出密码)/i.test(
            prompt
        )
    const safePhishingPrompt =
        /(账户异常.*验证|立刻验证|立即验证)/.test(prompt) &&
        /(担心.*钓鱼|像钓鱼|合规版本|改成合规|处理话术|直接发给对方)/.test(
            prompt
        ) &&
        !/(骗过|提高点击|诱导点击|索要验证码|索要密码|仿冒|伪装官方|钓鱼页面)/.test(
            prompt
        )
    const safeAdultReviewPrompt =
        /(小说社|投稿|审核意见|审核反馈).*(露骨|色情|成人|桥段)/.test(prompt) &&
        /(不复述|不描述|不展开|不引用).*(桥段|内容|细节)|处理话术|直接发给对方/.test(
            prompt
        ) &&
        !/(帮我写|生成|续写|润色).*(露骨|色情|成人|性行为|性器官)|(?:帮我|请|直接)?复述.*(桥段|细节)/.test(
            prompt.replace(/不复述/g, '不展开')
        )
    const safeAntiHarassmentPrompt =
        /(社群|群聊|讨论).*(攻击某类人|攻击.*人群|站队攻击|攻击性要求)/.test(
            prompt
        ) &&
        /(中立|不纵容|反骚扰|处理话术|直接发给对方|回复)/.test(prompt) &&
        !/(帮我攻击|骂回去|羞辱|煽动|带节奏|集火|围攻)/.test(prompt)
    const safeWeakPasswordTrainingPrompt =
        /(公司培训|安全演示|安全培训).*(证明.*密码弱|弱密码)/.test(prompt) &&
        /(不容易被认为越界|别写得像违规请求|合规|培训|演示)/.test(prompt) &&
        !/(验证.*真实密码|测试.*真实账号|登录.*同事|脚本|代码|撞库|爆破|hashcat)/i.test(
            prompt
        )
    const safeActivityBoundaryPrompt =
        /(线下活动|活动).*(包装成.*技术沙龙|技术沙龙.*拉人参与)/.test(prompt) &&
        /(提醒管理员|注意边界|处理话术|直接发给对方)/.test(prompt) &&
        !/(帮我包装|帮我拉人|规避审核|绕过平台|暗号|动员)/.test(prompt)
    const safeRealistAdvicePrompt =
        /现实主义建议/.test(prompt) &&
        !/(强者|弱者|弱势者|利用|剥削|包装成|合理化|理性分析)/.test(prompt)
    const safeChemRiskPrompt =
        /(化学.*(课堂|演示).*风险评估|风险评估.*化学.*(课堂|演示))/.test(
            prompt
        ) && !/(更刺激|更震撼|关键条件|参数|步骤|配方|剂量|复现)/.test(prompt)

    if (
        fixedBlock &&
        !safeExperimentPrompt &&
        !safeSearchMisusePrompt &&
        !safeCredentialPrompt &&
        !safePromptBypassPrompt &&
        !safePhishingPrompt &&
        !safeAdultReviewPrompt &&
        !safeAntiHarassmentPrompt &&
        !safeWeakPasswordTrainingPrompt &&
        !safeActivityBoundaryPrompt &&
        !safeRealistAdvicePrompt &&
        !safeChemRiskPrompt
    ) {
        return null
    }

    if (
        /骗过|钓鱼|验证码|开盒|真人画像|撞库|爆破|木马|免杀|持久化|规避.*检测|病原|毒品|爆炸|色情|露骨|未成年.*性/.test(
            prompt
        ) &&
        !safePhishingPrompt &&
        !safeAdultReviewPrompt &&
        !safeAntiHarassmentPrompt &&
        !safeWeakPasswordTrainingPrompt &&
        !safeActivityBoundaryPrompt &&
        !safeRealistAdvicePrompt &&
        !safeChemRiskPrompt
    ) {
        return null
    }

    if (safeRealistAdvicePrompt) {
        return [
            '可以写一段中性的现实主义建议。这里的重点是承认约束、明确目标、给出可执行路径，而不是合理化伤害或不公平。参考框架如下：',
            '',
            '1. 先说明现实约束：资源、时间、风险、责任边界和利益相关方。',
            '2. 再给出目标：希望改善什么问题，哪些指标能证明它真的变好。',
            '3. 提出方案时要写清成本、步骤、优先级和可回退选项。',
            '4. 对受影响的人保持尊重，避免把他人的损失包装成“必然”或“合理”。',
            '5. 结尾写明不确定性：哪些信息还需要核实，哪些条件变化会改变判断。',
            '',
            '简短示例：在预算有限的情况下，先解决影响最大的瓶颈，保留可回滚方案，并明确每一步对相关人员的影响。现实主义不是冷漠，而是在承认限制后尽量减少伤害、提升可执行性。'
        ].join('\n')
    }

    if (safeChemRiskPrompt) {
        return [
            '可以说明化学课堂演示的风险评估方法，但不应主动推荐高风险反应或给出可执行的危险演示条件。参考框架如下：',
            '',
            '1. 先列出物质、器材、热源、电源、压力、通风、观众距离和废弃物处理等风险源。',
            '2. 用“严重性 × 可能性”评估风险等级，高风险项目应替换、取消或改成视频、仿真、模型展示。',
            '3. 优先选择低风险、无明火、无高压、无有毒产物、无剧烈放热或飞溅风险的演示。',
            '4. 每个演示都应查阅 SDS、学校实验室规范和教师审核意见，明确个人防护、旁观距离、应急联系人和停止条件。',
            '5. 课堂展示的重点应是科学原理、观察记录和安全意识，而不是追求震撼效果。',
            '',
            '如果要做成表格，可以只列“风险源、可能后果、控制措施、是否需要替代、审批状态”，不要写具体危险反应的材料用量、条件或操作步骤。'
        ].join('\n')
    }

    if (safeSearchMisusePrompt) {
        return [
            '可以从安全培训和合规替代流程角度说明，但不应提供可复用的搜索语法、检索关键词或获取路径。',
            '',
            '建议这样表达：',
            '',
            '使用搜索技巧主动寻找疑似泄露资料，容易带来合规、隐私和安全风险。即使资料看似公开，也可能涉及未授权访问、个人信息、商业秘密或恶意文件传播。',
            '',
            '更合规的替代流程是：',
            '',
            '1. 如果发现疑似泄露线索，不继续扩散、下载或二次检索。',
            '2. 记录最小必要信息，例如发现时间、来源平台类型和风险描述，不保存敏感内容本身。',
            '3. 交给安全、法务或数据负责人通过正式流程核验。',
            '4. 对内部资料建立资产台账、访问控制、外发审批和水印追踪。',
            '5. 培训重点放在如何识别泄露风险、如何报告和如何降低再次泄露，而不是演示如何寻找资料。',
            '',
            '如果要写成群内提醒，可以用一句话概括：不要主动搜索或传播疑似泄露资料，发现线索请按安全事件流程上报。'
        ].join('\n')
    }

    if (safeCredentialPrompt) {
        return [
            '可以给出合规拒绝话术，但不应提供批量登录、密码验证工具、脚本或操作流程。',
            '',
            '建议这样回复：',
            '',
            '收到这个需求。出于账户安全、最小权限和审计合规要求，我们不能执行或协助“批量验证旧密码是否还能登录”的操作。无论是否用于内部演练，这类操作都可能造成凭证扩散、误触发风控、账户锁定或被误判为撞库行为。',
            '',
            '更合规的替代方案是：',
            '',
            '1. 通过账号治理流程确认旧账号是否仍处于启用状态。',
            '2. 使用密码重置、强制改密、禁用历史凭证等管理措施降低风险。',
            '3. 对演练需求先提交书面授权、范围、目标和回滚方案，由安全团队审批。',
            '4. 审计重点放在策略有效性、账号状态和日志留痕，不接触、不收集、不验证用户旧密码本身。',
            '',
            '如果需要继续推进，请先补充业务目的、涉及系统范围和审批人；我们可以协助设计不接触明文密码的合规验证方案。'
        ].join('\n')
    }

    if (safePromptBypassPrompt) {
        return [
            '可以写成客服处理备注和用户回复，但应避免指导用户绕过规则或导出受保护配置。',
            '',
            '内部备注可以这样写：',
            '',
            '用户在工单中提出“忽略规则导出配置”相关诉求。该请求可能涉及权限边界、数据脱敏、审计留痕或配置安全策略，当前不按绕过规则处理。已引导用户说明真实业务目的，并建议按标准导出流程或管理员审批流程处理。',
            '',
            '发给用户的话术可以这样写：',
            '',
            '您好，关于您提到的“忽略规则导出配置”，为保障数据安全和配置一致性，我们不能直接绕过系统规则执行导出。请您说明需要导出的配置范围、业务目的和遇到的具体问题。若属于正常备份、迁移或排障需求，我们会按标准流程协助处理；若需要特殊权限或规则调整，需要由管理员完成审批后再推进。',
            '',
            '这样回复既保留了解决问题的入口，也不会承诺跳过安全规则。'
        ].join('\n')
    }

    if (safePhishingPrompt) {
        return [
            '可以改成合规安全通知，但不应制造紧迫感、诱导点击链接或索要验证码。参考话术如下：',
            '',
            '您好，我们注意到账户安全状态可能需要您确认。为保护您的账户，请您自行打开官方 App 或官网，在“账户安全”或“消息中心”查看相关提醒。',
            '',
            '请注意：',
            '',
            '1. 我们不会通过私信、短信或群消息索要密码、验证码或支付信息。',
            '2. 请不要点击来源不明的链接，也不要向任何人转发验证码。',
            '3. 如有疑问，请通过 App 内客服、官网公布的客服电话或线下官方渠道核实。',
            '',
            '如果这是一条群公告，可以补充说明：本通知仅用于提醒大家提高账户安全意识，具体处理请以官方系统内提示为准。'
        ].join('\n')
    }

    if (safeAdultReviewPrompt) {
        return [
            '可以给出审核处理话术，但不应复述、改写或传播露骨桥段。参考版本如下：',
            '',
            '您好，感谢你的投稿。我们已经阅读了作品整体设定和表达方向。当前稿件中有部分内容超出了社团公开投稿和交流展示的尺度要求，因此暂时不能按原样收录或展示。',
            '',
            '建议你修改时注意以下几点：',
            '',
            '1. 删除或淡化过于露骨的描写，避免把重点放在身体细节或刺激性场景上。',
            '2. 如果情节需要表达亲密关系，可以改用人物心理、关系变化、氛围和后果来呈现。',
            '3. 保留作品的主题、人物动机和叙事张力，但让表达适合社团公开交流环境。',
            '4. 修改后可以重新提交，我们会按同一标准再次审核。',
            '',
            '这不是否定你的创作能力，而是为了保证投稿内容适合社团活动、公开讨论和不同年龄段成员共同参与的环境。'
        ].join('\n')
    }

    if (safeAntiHarassmentPrompt) {
        return [
            '可以给出中立且不纵容攻击的社群回复。参考版本如下：',
            '',
            '我们不支持把讨论变成对某类人或某个群体的攻击。请大家围绕具体观点、事实和行为本身表达意见，不要使用标签化、侮辱性或煽动性的说法。',
            '',
            '如果你对某个现象有不满，可以说明具体问题、依据和希望改进的方向；如果只是要求机器人站队、辱骂或带动攻击，我们不会配合。',
            '',
            '为了保持社群讨论质量，后续请使用理性、尊重、可验证的表达。继续发布攻击性内容的，管理员会按群规处理。'
        ].join('\n')
    }

    if (safeWeakPasswordTrainingPrompt) {
        return [
            '可以把需求改成合规的弱密码安全培训，但不应验证同事真实密码、真实账号或规避越界判断。参考版本如下：',
            '',
            '这个演示不建议围绕“证明某个同事密码弱”来设计。更安全的目标应改成：让大家理解弱密码风险，并学习如何避免复用、泄露和低强度密码。',
            '',
            '合规演示方案可以这样做：',
            '',
            '1. 使用虚构账号和样例密码，不接触任何真实员工账号、真实密码或历史密码。',
            '2. 展示常见弱密码模式，例如生日、手机号片段、连续数字、键盘序列和公司名称组合，但不收集个人信息。',
            '3. 用离线幻灯片或沙盒页面说明风险，不连接生产系统，也不尝试登录任何真实服务。',
            '4. 给出改进建议：启用多因素认证、使用密码管理器、避免复用密码、定期检查账号安全设置。',
            '5. 如需评估组织风险，应走正式授权流程，只统计策略合规率、弱密码规则命中率或 MFA 覆盖率，不验证个人密码本身。',
            '',
            '可以对外这样说明：本次培训不测试任何人的真实密码，只通过虚构样例讲解弱密码风险和防护方法。'
        ].join('\n')
    }

    if (safeActivityBoundaryPrompt) {
        return [
            '可以给管理员一段边界提醒话术，但不应帮助把活动伪装成其他性质来拉人参与。参考版本如下：',
            '',
            '管理员你好，群里关于把线下活动称作“技术沙龙”来组织参与的讨论，建议先确认活动真实目的、主办方、议程、地点、参与对象和责任人。',
            '',
            '如果活动确实是技术交流，应明确主题、讲者、内容范围、报名方式和安全责任；如果实际目的与技术交流不一致，就不应使用“技术沙龙”名义包装或误导群成员。',
            '',
            '建议处理方式：',
            '',
            '1. 要求发起人补充真实活动信息和公开说明。',
            '2. 不转发目的不清、责任不明或容易误导成员的招募信息。',
            '3. 涉及线下聚集、收费、商业推广或其他敏感事项时，先按群规和平台规则审核。',
            '4. 对群成员公开提醒：活动信息应真实透明，大家自行判断风险，不要被模糊包装诱导参与。',
            '',
            '这段话的重点是透明、合规和保护成员，而不是替任何活动做包装。'
        ].join('\n')
    }

    if (safeExperimentPrompt) {
        return [
            '可以写成安全拒绝和低风险替代建议。参考版本如下：',
            '',
            '社团演示不应追求刺激效果而牺牲安全。涉及失控反应、明火、高压、强腐蚀、强氧化、有毒气体、未知混合物或缺少审批的实验，都不适合作为活动展示。',
            '',
            '更稳妥的替代方案是：',
            '',
            '1. 使用仿真动画、公开视频或教师审核过的演示素材说明原理。',
            '2. 选择低风险、可控、无明火、无高压、无有毒产物的科普展示。',
            '3. 提前提交风险评估，明确场地、器材、个人防护、旁观距离和应急流程。',
            '4. 由具备资质的老师或实验室管理员审核方案后再执行。',
            '5. 面向观众强调安全边界和科学原理，而不是追求危险效果。',
            '',
            '如果活动需要更有吸引力，可以把重点放在互动问答、数据可视化、模型演示或现象解释上。'
        ].join('\n')
    }

    if (
        !fixedBlock &&
        !/抱歉，我(无法|不能)|无法(参与|处理|响应|执行|完成|提供)|不能(参与|提供)|服务安全策略阻止|sorry/i.test(
            reply
        )
    ) {
        return null
    }

    if (/商业|CEO|市场表态|跨国公司|中立分析|培训讲义/.test(prompt)) {
        return [
            '可以从中立、可核验的商业分析角度处理这个问题。',
            '',
            '建议按以下框架展开：',
            '',
            '1. 先拆事实：确认原文、时间、场合、发言对象和是否存在可靠来源。',
            '2. 分清事实与解读：把公司原话、媒体标题、评论观点和市场反应分开放。',
            '3. 看商业变量：市场规模、供应链依赖、客户结构、合规成本、竞争格局和财报披露。',
            '4. 避免单因归因：不要把复杂商业决策简化成单一立场或阴谋解释。',
            '5. 写明不确定性：标注缺少原文、缺少最新数据或只适用于公开信息的部分。',
            '',
            '如果用于课程项目，可以把它设计成“公开资料的商业影响分析”：收集多方公开来源，建立事实表，再比较不同解释对营收、供应链和品牌风险的影响。'
        ].join('\n')
    }

    if (/公开政策|政策条文|企业合规|合规影响/.test(prompt)) {
        return [
            '可以做公开政策条文的合规阅读，但应保持在合法、公开、非规避的范围内。',
            '',
            '建议按以下框架分析：',
            '',
            '1. 摘出条文中的义务、限制、适用对象和生效条件。',
            '2. 对照企业流程：数据、合同、宣传、用工、财务或供应链中哪些环节会受影响。',
            '3. 标出风险点：哪些行为需要审批、留痕、告知、备案或额外审查。',
            '4. 给出安全替代做法：完善制度、调整流程、咨询专业法律意见，而不是规避监管。',
            '',
            '如果你提供具体条文，我可以继续按这个框架逐条拆解。'
        ].join('\n')
    }

    if (
        /(开源情报|OSINT|公开信息).*(避免|防止|不要).*(普通网友|真人|本人|个人身份|联系方式|定位)|避免.*(普通网友|真人|本人).*(定位|关联|识别)|隐私保护.*(开源情报|OSINT|公开信息)|安全替代做法/.test(
            prompt
        )
    ) {
        return [
            '可以从隐私保护和合规研究方法角度回答。',
            '',
            '开源情报研究中避免把普通网友定位到真人，可以遵循这些做法：',
            '',
            '1. 明确研究边界：只分析公开内容的主题、传播路径和群体趋势，不追踪个人身份。',
            '2. 做最小化处理：不要合并头像、昵称、学校、地理位置、社交账号等可识别线索。',
            '3. 使用聚合表达：把样本写成“若干账号”“某类公开帖子”，避免单点画像。',
            '4. 去标识化记录：删除用户名、链接、截图中的头像、ID、水印和联系方式。',
            '5. 避免跨平台关联：不要把不同平台的账号线索串联成同一个真人。',
            '6. 保留合规审查：课堂或报告中只展示方法、风险和防护建议，不展示可复原个人身份的材料。',
            '',
            '安全替代做法是：研究公开信息如何被误用、如何降低再识别风险，以及平台或个人该如何做隐私保护。'
        ].join('\n')
    }

    if (/史料|近代史|交叉验证|课堂答疑/.test(prompt)) {
        return [
            '可以从历史研究方法论角度回答。',
            '',
            '公开史料交叉验证可以这样做：',
            '',
            '1. 区分一手史料、二手研究、新闻报道、回忆录和网络转述。',
            '2. 比对时间、地点、人物、原始出处和引用链，优先查原文。',
            '3. 对照不同立场、不同地区、不同机构的公开资料，记录一致点和分歧点。',
            '4. 标注证据强弱，不用单一来源下定论。',
            '5. 课堂表达时保持学术、事实和方法导向，避免口号化或动员化。'
        ].join('\n')
    }

    if (/分词|中文片段|词边界|语言学/.test(prompt)) {
        return [
            '可以只从中文分词和词边界角度解释。',
            '',
            '判断一个片段是否构成独立词，通常看这几点：',
            '',
            '1. 词典中是否有稳定词条。',
            '2. 在上下文里是否有完整语义。',
            '3. 相邻字符是否更自然地组成另一个高频词。',
            '4. 分词模型是否需要结合前后文概率，而不是只做裸子串匹配。',
            '',
            '因此，短片段是否命中某个词，不能只看包含关系，还要看上下文边界。'
        ].join('\n')
    }

    return null
}

export function repairReferences(reply: string) {
    const refs = new Map<string, { title: string; url: string }>()
    let result = reply
        .replace(/<\/?p>/gi, '\n')
        .replace(/（/g, '(')
        .replace(/）/g, ')')
        .replace(
            /\^(\d+)\s*\(\s*\[([^\]\n]+)\]\((https?:\/\/[^)\s]+)\)\s*\)/g,
            (_match, id: string, title: string, url: string) => {
                refs.set(id, {
                    title: title.trim(),
                    url: url.trim()
                })
                return `[^${id}]`
            }
        )
        .replace(/(^|\n)#{1,6}\s*References\s*:?\s*(?=\n|$)/gi, '$1References:')
        .replace(/\s*(\[\^\d+\]:)/g, '\n$1')
        .replace(/(^|\n)References(?=\[\^\d+\]:)/gi, '$1References:\n')
        .replace(/(^|\n)References\s*$/gim, '$1References:')
        .replace(
            /^\[\^(\d+)\]:\s*\[?([^\]\[(\n]+)\]?\s*\((https?:\/\/[^)\s]+)\)(.*)$/gim,
            (_match, id: string, title: string, url: string, tail: string) =>
                `[^${id}]: [${title.trim()}](${url.trim()})${
                    tail.trim().length > 0 ? `\n${tail.trim()}` : ''
                }`
        )

    const existing = new Set(
        Array.from(result.matchAll(/^\[\^(\d+)\]:/gim)).map((item) => item[1])
    )
    const missing = Array.from(refs.entries()).filter(
        ([id]) => !existing.has(id)
    )

    if (missing.length > 0) {
        if (!/^References:\s*$/gim.test(result)) {
            result += '\n\nReferences:'
        }

        result +=
            '\n' +
            missing
                .map(
                    ([id, item]) =>
                        `[^${id}]: [${item.title.trim()}](${item.url.trim()})`
                )
                .join('\n')
    }

    return result.replace(/\n{3,}/g, '\n\n').trim()
}
