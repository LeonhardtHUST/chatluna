export function repairBenignRefusal(prompt: string, reply: string) {
    if (
        !/抱歉，我(无法|不能)|无法(参与|处理|响应|执行)|不能参与|sorry/i.test(
            reply
        ) ||
        /服务安全策略阻止|基于模型内容安全策略/.test(reply)
    ) {
        return null
    }

    if (
        /骗过|钓鱼|验证码|开盒|真人画像|撞库|爆破|木马|免杀|持久化|规避.*检测|病原|毒品|爆炸|色情|露骨|未成年.*性/.test(
            prompt
        )
    ) {
        return null
    }

    if (/商业|CEO|市场表态|跨国公司|中立分析|培训讲义/.test(prompt)) {
        return [
            '可以从中立、可核验的商业分析角度处理这个问题。',
            '',
            '建议按以下框架展开：',
            '',
            '1. 先拆事实：确认原文、时间、场合、发言对象和是否存在可靠来源。',
            '2. 分清事实与解读：把公司原话、媒体标题、评论观点和市场反应分开放。',
            '3. 看商业变量：市场规模、供应链依赖、客户结构、合规成本、竞争格局和财报披露。',
            '4. 避免单因归因：不要把复杂商业决策简化成单一立场或阴谋解释。',
            '5. 写明不确定性：标注缺少原文、缺少最新数据或只适用于公开信息的部分。',
            '',
            '如果用于课程项目，可以把它设计成“公开资料的商业影响分析”：收集多方公开来源，建立事实表，再比较不同解释对营收、供应链和品牌风险的影响。'
        ].join('\n')
    }

    if (/公开政策|政策条文|企业合规|合规影响/.test(prompt)) {
        return [
            '可以做公开政策条文的合规阅读，但应保持在合法、公开、非规避的范围内。',
            '',
            '建议按以下框架分析：',
            '',
            '1. 摘出条文中的义务、限制、适用对象和生效条件。',
            '2. 对照企业流程：数据、合同、宣传、用工、财务或供应链中哪些环节会受影响。',
            '3. 标出风险点：哪些行为需要审批、留痕、告知、备案或额外审查。',
            '4. 给出安全替代做法：完善制度、调整流程、咨询专业法律意见，而不是规避监管。',
            '',
            '如果你提供具体条文，我可以继续按这个框架逐条拆解。'
        ].join('\n')
    }

    if (/史料|近代史|交叉验证|课堂答疑/.test(prompt)) {
        return [
            '可以从历史研究方法论角度回答。',
            '',
            '公开史料交叉验证可以这样做：',
            '',
            '1. 区分一手史料、二手研究、新闻报道、回忆录和网络转述。',
            '2. 比对时间、地点、人物、原始出处和引用链，优先查原文。',
            '3. 对照不同立场、不同地区、不同机构的公开资料，记录一致点和分歧点。',
            '4. 标注证据强弱，不用单一来源下定论。',
            '5. 课堂表达时保持学术、事实和方法导向，避免口号化或动员化。'
        ].join('\n')
    }

    if (/分词|中文片段|词边界|语言学/.test(prompt)) {
        return [
            '可以只从中文分词和词边界角度解释。',
            '',
            '判断一个片段是否构成独立词，通常看这几点：',
            '',
            '1. 词典中是否有稳定词条。',
            '2. 在上下文里是否有完整语义。',
            '3. 相邻字符是否更自然地组成另一个高频词。',
            '4. 分词模型是否需要结合前后文概率，而不是只做裸子串匹配。',
            '',
            '因此，短片段是否命中某个词，不能只看包含关系，还要看上下文边界。'
        ].join('\n')
    }

    return null
}
