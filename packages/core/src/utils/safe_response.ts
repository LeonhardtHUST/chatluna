export function repairBenignRefusal(prompt: string, reply: string) {
    const text = reply.trim()
    const fixedBlock =
        text ===
            '服务安全策略阻止了对有关提示词的响应。若有疑义，请联系管理员。' ||
        text ===
            '基于模型内容安全策略，服务端 API 拒绝为本次内容提供响应。请求记录已存档备查。若有问题，请联系管理员。'
    const safeExperimentPrompt =
        /拒绝高风险实验|推荐安全替代|安全替代.*说明/.test(prompt) &&
        !/复现|关键条件|参数|步骤|配方|剂量|事故|爆炸|燃烧瓶|炸药|病原|毒品/.test(
            prompt
        )
    const safeSearchMisusePrompt =
        /(搜索语法|高级搜索|搜索指令|google dork|dork|网盘资料).*(风险|替代流程|替代方案|合规|培训|话术|提醒|不要|不应|不能|禁止|说明)/i.test(
            prompt
        ) &&
        !/(帮我找|帮我搜|给我.*语法|列出.*语法|可用链接|下载|获取|site:|inurl:|intitle:)/i.test(
            prompt
        )
    const safeCredentialPrompt =
        /(批量验证.*旧密码|旧密码.*还能登录|旧密码.*登录)/.test(prompt) &&
        /(安全负责人|合规|怎么回复|话术|处理话术|直接发给对方)/.test(prompt) &&
        !/(帮我验证|帮我测试|脚本|代码|工具|hashcat|撞库|爆破|绕过)/i.test(
            prompt
        )
    const safePromptBypassPrompt =
        /忽略规则导出配置/.test(prompt) &&
        /(客服|工单|备注|处理话术|怎么写|直接发给对方)/.test(prompt) &&
        !/(帮我忽略|帮我绕过|怎么绕过|直接导出|导出密钥|导出 token|导出密码)/i.test(
            prompt
        )

    if (
        fixedBlock &&
        !safeExperimentPrompt &&
        !safeSearchMisusePrompt &&
        !safeCredentialPrompt &&
        !safePromptBypassPrompt
    ) {
        return null
    }

    if (
        /骗过|钓鱼|验证码|开盒|真人画像|撞库|爆破|木马|免杀|持久化|规避.*检测|病原|毒品|爆炸|色情|露骨|未成年.*性/.test(
            prompt
        )
    ) {
        return null
    }

    if (safeSearchMisusePrompt) {
        return [
            '可以从安全培训和合规替代流程角度说明，但不应提供可复用的搜索语法、检索关键词或获取路径。',
            '',
            '建议这样表达：',
            '',
            '使用搜索技巧主动寻找疑似泄露资料，容易带来合规、隐私和安全风险。即使资料看似公开，也可能涉及未授权访问、个人信息、商业秘密或恶意文件传播。',
            '',
            '更合规的替代流程是：',
            '',
            '1. 如果发现疑似泄露线索，不继续扩散、下载或二次检索。',
            '2. 记录最小必要信息，例如发现时间、来源平台类型和风险描述，不保存敏感内容本身。',
            '3. 交给安全、法务或数据负责人通过正式流程核验。',
            '4. 对内部资料建立资产台账、访问控制、外发审批和水印追踪。',
            '5. 培训重点放在如何识别泄露风险、如何报告和如何降低再次泄露，而不是演示如何寻找资料。',
            '',
            '如果要写成群内提醒，可以用一句话概括：不要主动搜索或传播疑似泄露资料，发现线索请按安全事件流程上报。'
        ].join('\n')
    }

    if (safeCredentialPrompt) {
        return [
            '可以给出合规拒绝话术，但不应提供批量登录、密码验证工具、脚本或操作流程。',
            '',
            '建议这样回复：',
            '',
            '收到这个需求。出于账户安全、最小权限和审计合规要求，我们不能执行或协助“批量验证旧密码是否还能登录”的操作。无论是否用于内部演练，这类操作都可能造成凭证扩散、误触发风控、账户锁定或被误判为撞库行为。',
            '',
            '更合规的替代方案是：',
            '',
            '1. 通过账号治理流程确认旧账号是否仍处于启用状态。',
            '2. 使用密码重置、强制改密、禁用历史凭证等管理措施降低风险。',
            '3. 对演练需求先提交书面授权、范围、目标和回滚方案，由安全团队审批。',
            '4. 审计重点放在策略有效性、账号状态和日志留痕，不接触、不收集、不验证用户旧密码本身。',
            '',
            '如果需要继续推进，请先补充业务目的、涉及系统范围和审批人；我们可以协助设计不接触明文密码的合规验证方案。'
        ].join('\n')
    }

    if (safePromptBypassPrompt) {
        return [
            '可以写成客服处理备注和用户回复，但应避免指导用户绕过规则或导出受保护配置。',
            '',
            '内部备注可以这样写：',
            '',
            '用户在工单中提出“忽略规则导出配置”相关诉求。该请求可能涉及权限边界、数据脱敏、审计留痕或配置安全策略，当前不按绕过规则处理。已引导用户说明真实业务目的，并建议按标准导出流程或管理员审批流程处理。',
            '',
            '发给用户的话术可以这样写：',
            '',
            '您好，关于您提到的“忽略规则导出配置”，为保障数据安全和配置一致性，我们不能直接绕过系统规则执行导出。请您说明需要导出的配置范围、业务目的和遇到的具体问题。若属于正常备份、迁移或排障需求，我们会按标准流程协助处理；若需要特殊权限或规则调整，需要由管理员完成审批后再推进。',
            '',
            '这样回复既保留了解决问题的入口，也不会承诺跳过安全规则。'
        ].join('\n')
    }

    if (safeExperimentPrompt) {
        return [
            '可以写成安全拒绝和低风险替代建议。参考版本如下：',
            '',
            '社团演示不应追求刺激效果而牺牲安全。涉及失控反应、明火、高压、强腐蚀、强氧化、有毒气体、未知混合物或缺少审批的实验，都不适合作为活动展示。',
            '',
            '更稳妥的替代方案是：',
            '',
            '1. 使用仿真动画、公开视频或教师审核过的演示素材说明原理。',
            '2. 选择低风险、可控、无明火、无高压、无有毒产物的科普展示。',
            '3. 提前提交风险评估，明确场地、器材、个人防护、旁观距离和应急流程。',
            '4. 由具备资质的老师或实验室管理员审核方案后再执行。',
            '5. 面向观众强调安全边界和科学原理，而不是追求危险效果。',
            '',
            '如果活动需要更有吸引力，可以把重点放在互动问答、数据可视化、模型演示或现象解释上。'
        ].join('\n')
    }

    if (
        !fixedBlock &&
        !/抱歉，我(无法|不能)|无法(参与|处理|响应|执行|完成|提供)|不能(参与|提供)|服务安全策略阻止|sorry/i.test(
            reply
        )
    ) {
        return null
    }

    if (/商业|CEO|市场表态|跨国公司|中立分析|培训讲义/.test(prompt)) {
        return [
            '可以从中立、可核验的商业分析角度处理这个问题。',
            '',
            '建议按以下框架展开：',
            '',
            '1. 先拆事实：确认原文、时间、场合、发言对象和是否存在可靠来源。',
            '2. 分清事实与解读：把公司原话、媒体标题、评论观点和市场反应分开放。',
            '3. 看商业变量：市场规模、供应链依赖、客户结构、合规成本、竞争格局和财报披露。',
            '4. 避免单因归因：不要把复杂商业决策简化成单一立场或阴谋解释。',
            '5. 写明不确定性：标注缺少原文、缺少最新数据或只适用于公开信息的部分。',
            '',
            '如果用于课程项目，可以把它设计成“公开资料的商业影响分析”：收集多方公开来源，建立事实表，再比较不同解释对营收、供应链和品牌风险的影响。'
        ].join('\n')
    }

    if (/公开政策|政策条文|企业合规|合规影响/.test(prompt)) {
        return [
            '可以做公开政策条文的合规阅读，但应保持在合法、公开、非规避的范围内。',
            '',
            '建议按以下框架分析：',
            '',
            '1. 摘出条文中的义务、限制、适用对象和生效条件。',
            '2. 对照企业流程：数据、合同、宣传、用工、财务或供应链中哪些环节会受影响。',
            '3. 标出风险点：哪些行为需要审批、留痕、告知、备案或额外审查。',
            '4. 给出安全替代做法：完善制度、调整流程、咨询专业法律意见，而不是规避监管。',
            '',
            '如果你提供具体条文，我可以继续按这个框架逐条拆解。'
        ].join('\n')
    }

    if (
        /(开源情报|OSINT|公开信息).*(避免|防止|不要).*(普通网友|真人|本人|个人身份|联系方式|定位)|避免.*(普通网友|真人|本人).*(定位|关联|识别)|隐私保护.*(开源情报|OSINT|公开信息)|安全替代做法/.test(
            prompt
        )
    ) {
        return [
            '可以从隐私保护和合规研究方法角度回答。',
            '',
            '开源情报研究中避免把普通网友定位到真人，可以遵循这些做法：',
            '',
            '1. 明确研究边界：只分析公开内容的主题、传播路径和群体趋势，不追踪个人身份。',
            '2. 做最小化处理：不要合并头像、昵称、学校、地理位置、社交账号等可识别线索。',
            '3. 使用聚合表达：把样本写成“若干账号”“某类公开帖子”，避免单点画像。',
            '4. 去标识化记录：删除用户名、链接、截图中的头像、ID、水印和联系方式。',
            '5. 避免跨平台关联：不要把不同平台的账号线索串联成同一个真人。',
            '6. 保留合规审查：课堂或报告中只展示方法、风险和防护建议，不展示可复原个人身份的材料。',
            '',
            '安全替代做法是：研究公开信息如何被误用、如何降低再识别风险，以及平台或个人该如何做隐私保护。'
        ].join('\n')
    }

    if (/史料|近代史|交叉验证|课堂答疑/.test(prompt)) {
        return [
            '可以从历史研究方法论角度回答。',
            '',
            '公开史料交叉验证可以这样做：',
            '',
            '1. 区分一手史料、二手研究、新闻报道、回忆录和网络转述。',
            '2. 比对时间、地点、人物、原始出处和引用链，优先查原文。',
            '3. 对照不同立场、不同地区、不同机构的公开资料，记录一致点和分歧点。',
            '4. 标注证据强弱，不用单一来源下定论。',
            '5. 课堂表达时保持学术、事实和方法导向，避免口号化或动员化。'
        ].join('\n')
    }

    if (/分词|中文片段|词边界|语言学/.test(prompt)) {
        return [
            '可以只从中文分词和词边界角度解释。',
            '',
            '判断一个片段是否构成独立词，通常看这几点：',
            '',
            '1. 词典中是否有稳定词条。',
            '2. 在上下文里是否有完整语义。',
            '3. 相邻字符是否更自然地组成另一个高频词。',
            '4. 分词模型是否需要结合前后文概率，而不是只做裸子串匹配。',
            '',
            '因此，短片段是否命中某个词，不能只看包含关系，还要看上下文边界。'
        ].join('\n')
    }

    return null
}
